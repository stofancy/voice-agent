# ── Helpers ───────────────────────────────────────────────────────────────────

def _similarity(a: str, b: str) -> float:
    """Sequence-match ratio between two strings (0–1)."""
    # Normalise: strip spaces, lower-case for CJK-safe comparison
    a = a.strip().lower().replace(" ", "")
    b = b.strip().lower().replace(" ", "")
    return SequenceMatcher(None, a, b).ratio()


async def _ensure_fixture(key: str, tts_client, audio_fixtures_dir) -> str:
    """Return fixture path, generating the WAV via TTS if it doesn't exist."""
    path = str(audio_fixtures_dir / f"{key}.wav")
    if not os.path.exists(path):
        text, _ = SCENARIOS[key]
        pcm, _, _ = await collect_tts_stream(tts_client, text)
        assert pcm, f"TTS returned no audio when creating fixture for {key}"
        save_pcm_as_wav(pcm, path)
    return path


# ── Latency tests ─────────────────────────────────────────────────────────────

class TestSTTLatency:
    """
    Measure how long the STT API takes per scenario.
    Also verifies that a non-empty string is returned.
    """

    @pytest.mark.asyncio
    async def test_stt_latency_short_zh(
        self, stt_client, tts_client, audio_fixtures_dir, latency_tracker
    ):
        path = await _ensure_fixture("short_zh", tts_client, audio_fixtures_dir)
        audio, sr = read_wav_to_numpy(path)

        t0 = time.perf_counter()
        text, ok = await stt_client.transcribe(audio, sample_rate=sr)
        latency_ms = (time.perf_counter() - t0) * 1000

        assert ok, f"STT returned failure: {text}"
        assert text.strip(), "STT returned empty string"
        latency_tracker.record("stt_latency_ms", latency_ms, scenario="short_zh")
        print(f"\nshort_zh STT: {latency_ms:.0f}ms → \"{text}\"")

