# ── Silence / edge-case handling ──────────────────────────────────────────────

class TestSTTEdgeCases:
    """Verify graceful handling of unusual inputs."""

    @pytest.mark.asyncio
    async def test_very_short_audio(self, stt_client):
        """0.3 s of silence – API should return empty text or error without crashing."""
        silence = np.zeros(int(0.3 * 16000), dtype=np.float32)
        text, _ = await stt_client.transcribe(silence, sample_rate=16000)
        # We don't assert on content, just that it doesn't raise
        assert isinstance(text, str)

    @pytest.mark.asyncio
    async def test_pure_tone_audio(self, stt_client):
        """440 Hz sine wave – shouldn't crash, should return empty or noise text."""
        t = np.linspace(0, 1.0, 16000, endpoint=False)
        tone = (np.sin(2 * np.pi * 440 * t) * 0.5).astype(np.float32)
        text, _ = await stt_client.transcribe(tone, sample_rate=16000)
        assert isinstance(text, str)
        print(f"\npure tone transcription: {text!r}")
